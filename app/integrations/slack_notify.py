"""Slack notification service for posting RCA reports.

Sends formatted investigation reports to Slack channels via webhooks.
"""

from __future__ import annotations

import logging
from typing import Any

import httpx

from app.config import get_settings

log = logging.getLogger("omnipotent.integrations.slack_notify")


def is_slack_configured() -> bool:
    """Check if Slack notifications are configured."""
    s = get_settings()
    return bool(s.slack_bot_token or s.slack_webhook_url)


def _format_report_blocks(report: dict[str, Any], query: str) -> list[dict[str, Any]]:
    """Format an investigation report as Slack blocks."""
    blocks: list[dict[str, Any]] = []

    # Header
    blocks.append({
        "type": "header",
        "text": {
            "type": "plain_text",
            "text": "Investigation Report",
            "emoji": True
        }
    })

    # Query
    blocks.append({
        "type": "section",
        "text": {
            "type": "mrkdwn",
            "text": f"*Query:* {query}"
        }
    })

    blocks.append({"type": "divider"})

    # Root Cause
    if report.get("root_cause"):
        confidence = report.get("confidence", "unknown")
        confidence_emoji = {
            "high": ":white_check_mark:",
            "medium": ":warning:",
            "low": ":question:"
        }.get(confidence, ":grey_question:")

        blocks.append({
            "type": "section",
            "text": {
                "type": "mrkdwn",
                "text": f"*Root Cause* {confidence_emoji}\n{report['root_cause']}"
            }
        })

    # Evidence
    if report.get("evidence") and isinstance(report["evidence"], list):
        evidence_text = "\n".join(f"• {e}" for e in report["evidence"][:5])
        blocks.append({
            "type": "section",
            "text": {
                "type": "mrkdwn",
                "text": f"*Evidence:*\n{evidence_text}"
            }
        })

    # Affected Services
    if report.get("affected_services") and isinstance(report["affected_services"], list):
        services = ", ".join(f"`{s}`" for s in report["affected_services"])
        blocks.append({
            "type": "section",
            "text": {
                "type": "mrkdwn",
                "text": f"*Affected Services:* {services}"
            }
        })

    # Resolution / Recommendation
    if report.get("resolution"):
        blocks.append({
            "type": "section",
            "text": {
                "type": "mrkdwn",
                "text": f"*Resolution:*\n{report['resolution']}"
            }
        })
    elif report.get("recommendation"):
        blocks.append({
            "type": "section",
            "text": {
                "type": "mrkdwn",
                "text": f"*Recommendation:*\n{report['recommendation']}"
            }
        })

    # Footer
    blocks.append({"type": "divider"})
    blocks.append({
        "type": "context",
        "elements": [
            {
                "type": "mrkdwn",
                "text": f":robot_face: Generated by OmniPotent | Confidence: *{report.get('confidence', 'N/A')}*"
            }
        ]
    })

    return blocks


async def post_to_slack(
    report: dict[str, Any],
    query: str,
    channel: str | None = None,
    webhook_url: str | None = None,
) -> dict[str, Any]:
    """Post an investigation report to Slack.

    Args:
        report: The investigation report dict
        query: The original investigation query
        channel: Slack channel ID (for bot token method)
        webhook_url: Slack webhook URL (alternative to bot token)

    Returns:
        Result dict with success status and message
    """
    s = get_settings()

    # Build message blocks
    blocks = _format_report_blocks(report, query)

    # Fallback text for notifications
    fallback_text = f"Investigation Report: {report.get('root_cause', query)[:100]}"

    try:
        # Method 1: Webhook URL (simpler)
        url = webhook_url or getattr(s, 'slack_webhook_url', None)
        if url:
            async with httpx.AsyncClient(timeout=30) as client:
                resp = await client.post(url, json={
                    "text": fallback_text,
                    "blocks": blocks
                })
                if resp.status_code == 200:
                    return {"success": True, "message": "Report posted to Slack"}
                else:
                    log.warning("Slack webhook failed: %s", resp.text)
                    return {"success": False, "message": f"Slack error: {resp.status_code}"}

        # Method 2: Bot Token (more features)
        bot_token = s.slack_bot_token
        target_channel = channel or s.slack_channel
        if bot_token and target_channel:
            async with httpx.AsyncClient(timeout=30) as client:
                resp = await client.post(
                    "https://slack.com/api/chat.postMessage",
                    headers={"Authorization": f"Bearer {bot_token}"},
                    json={
                        "channel": target_channel,
                        "text": fallback_text,
                        "blocks": blocks
                    }
                )
                data = resp.json()
                if data.get("ok"):
                    return {"success": True, "message": "Report posted to Slack", "ts": data.get("ts")}
                else:
                    log.warning("Slack API error: %s", data.get("error"))
                    return {"success": False, "message": f"Slack error: {data.get('error')}"}

        return {"success": False, "message": "Slack not configured"}

    except httpx.HTTPError as e:
        log.exception("Failed to post to Slack")
        return {"success": False, "message": f"HTTP error: {str(e)}"}
    except Exception as e:
        log.exception("Unexpected error posting to Slack")
        return {"success": False, "message": str(e)}


async def send_quick_message(
    text: str,
    channel: str | None = None,
) -> dict[str, Any]:
    """Send a simple text message to Slack."""
    s = get_settings()

    try:
        # Try webhook first
        url = getattr(s, 'slack_webhook_url', None)
        if url:
            async with httpx.AsyncClient(timeout=30) as client:
                resp = await client.post(url, json={"text": text})
                return {"success": resp.status_code == 200}

        # Then bot token
        bot_token = s.slack_bot_token
        target_channel = channel or s.slack_channel
        if bot_token and target_channel:
            async with httpx.AsyncClient(timeout=30) as client:
                resp = await client.post(
                    "https://slack.com/api/chat.postMessage",
                    headers={"Authorization": f"Bearer {bot_token}"},
                    json={"channel": target_channel, "text": text}
                )
                data = resp.json()
                return {"success": data.get("ok", False)}

        return {"success": False, "message": "Slack not configured"}

    except Exception as e:
        log.exception("Failed to send Slack message")
        return {"success": False, "message": str(e)}
