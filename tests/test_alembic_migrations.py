"""The Alembic chain must run, and must match the ORM.

Two things were broken here at once. `migrations/env.py` never imported
`app.oncall.models`, so autogenerate could not see the 17 `oncall_*` tables —
they were declared in the ORM and created by no migration, and the next
autogenerate would have read their absence as "drop these". And migration 001
used `postgresql.JSONB` directly, so against the default SQLite URL every
`alembic upgrade head` died on `CompileError: ... can't render element of
type JSONB` before creating a single table.

`test_no_drift_between_migrations_and_models` is the one that keeps this
honest: it fails the moment a model changes without a matching revision.
"""

