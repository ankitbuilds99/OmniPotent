def _tables(db_path: Path) -> set[str]:
    with sqlite3.connect(db_path) as conn:
        rows = conn.execute("SELECT name FROM sqlite_master WHERE type='table'")
        return {r[0] for r in rows}


@pytest.fixture
def migrated(tmp_path, monkeypatch):
    """A SQLite database at `head`, plus the Config that got it there."""
    db_path = tmp_path / "migrations.db"
    monkeypatch.setenv("COPILOT_DATABASE_URL", f"sqlite+aiosqlite:///{db_path}")
    monkeypatch.delenv("DATABASE_URL", raising=False)

    config = Config(str(ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(ROOT / "migrations"))
    command.upgrade(config, "head")
    return config, db_path


def test_upgrade_head_creates_every_table(migrated):
    _, db_path = migrated
    tables = _tables(db_path)

    assert CORE_TABLES <= tables
    # The whole point of revision 002: 17 tables that no migration created.
    assert ONCALL_TABLES <= tables


def test_no_drift_between_migrations_and_models(migrated):
    config, _ = migrated
    try:
        command.check(config)
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
        pytest.fail(f"models and migrations disagree; add a revision:\n{exc}")


def test_downgrade_to_base_is_clean(migrated):
    config, db_path = migrated

    command.downgrade(config, "base")

    remaining = _tables(db_path)
    assert not (CORE_TABLES & remaining)
    assert not (ONCALL_TABLES & remaining)


def test_database_url_is_honoured_as_a_fallback(tmp_path, monkeypatch):
    """docker-compose, the k8s Job and the Helm chart all set DATABASE_URL.

    env.py read only COPILOT_DATABASE_URL, so every scripted upgrade silently
    migrated the local SQLite default instead of the database the app uses.
    """
    db_path = tmp_path / "fallback.db"
    monkeypatch.delenv("COPILOT_DATABASE_URL", raising=False)
    monkeypatch.setenv("DATABASE_URL", f"sqlite:///{db_path}")

    config = Config(str(ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(ROOT / "migrations"))
    command.upgrade(config, "head")

    assert db_path.is_file()
    assert ONCALL_TABLES <= _tables(db_path)


def test_upgrade_creates_the_sqlite_parent_directory(tmp_path, monkeypatch):
    """The documented default is `sqlite:///data/copilot.db` and `data/` is untracked.

    SQLite will not create the directory holding the database file, it just
    fails with "unable to open database file", so on a fresh clone
    `alembic upgrade head` died before running a single revision.
    """
    db_path = tmp_path / "not" / "created" / "yet" / "copilot.db"
    assert not db_path.parent.exists()
    monkeypatch.setenv("COPILOT_DATABASE_URL", f"sqlite:///{db_path}")
    monkeypatch.delenv("DATABASE_URL", raising=False)

    config = Config(str(ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(ROOT / "migrations"))
    command.upgrade(config, "head")

    assert db_path.is_file()
    assert CORE_TABLES <= _tables(db_path)
