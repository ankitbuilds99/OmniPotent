/**
 * Export investigation reports to various formats
 */

interface Investigation {
  id: string
  thread_id: string
  query: string
  summary: string | null
  status: string
  tokens_used: number
  latency_ms: number | null
  created_at: string
  completed_at: string | null
  report: Record<string, unknown> | null
}

interface ExportOptions {
  format: 'markdown' | 'json' | 'html'
  includeMetadata?: boolean
}

/**
 * Generate Markdown report
 */
function toMarkdown(investigation: Investigation, includeMetadata = true): string {
  const lines: string[] = []

  // Title
  lines.push(`# Investigation Report`)
  lines.push('')
  lines.push(`## Query`)
  lines.push(investigation.query)
  lines.push('')

  // Summary
  if (investigation.summary) {
    lines.push(`## Summary`)
    lines.push(investigation.summary)
    lines.push('')
  }

  // Report details
  if (investigation.report) {
    lines.push(`## Findings`)
    lines.push('')

    const report = investigation.report as Record<string, unknown>

    if (report.root_cause) {
      lines.push(`### Root Cause`)
      lines.push(String(report.root_cause))
      lines.push('')
    }

    if (report.confidence) {
      lines.push(`**Confidence:** ${report.confidence}`)
      lines.push('')
    }

    if (report.evidence && Array.isArray(report.evidence)) {
      lines.push(`### Evidence`)
      report.evidence.forEach((e: unknown) => {
        lines.push(`- ${String(e)}`)
      })
      lines.push('')
    }

    if (report.affected_services && Array.isArray(report.affected_services)) {
      lines.push(`### Affected Services`)
      report.affected_services.forEach((s: unknown) => {
        lines.push(`- ${String(s)}`)
      })
      lines.push('')
    }

    if (report.resolution) {
      lines.push(`### Resolution`)
      lines.push(String(report.resolution))
      lines.push('')
    }

    if (report.recommendation) {
      lines.push(`### Recommendation`)
      lines.push(String(report.recommendation))
      lines.push('')
    }

    if (report.timeline && Array.isArray(report.timeline)) {
      lines.push(`### Timeline`)
      report.timeline.forEach((t: unknown) => {
        if (typeof t === 'object' && t !== null) {
          const entry = t as Record<string, unknown>
          lines.push(`- **${entry.time}**: ${entry.event}`)
        }
      })
      lines.push('')
    }
  }

  // Metadata
  if (includeMetadata) {
    lines.push(`---`)
    lines.push('')
    lines.push(`## Metadata`)
    lines.push(`- **Status:** ${investigation.status}`)
    lines.push(`- **Created:** ${new Date(investigation.created_at).toLocaleString()}`)
    if (investigation.completed_at) {
      lines.push(`- **Completed:** ${new Date(investigation.completed_at).toLocaleString()}`)
    }
    lines.push(`- **Tokens Used:** ${investigation.tokens_used.toLocaleString()}`)
    if (investigation.latency_ms) {
      lines.push(`- **Latency:** ${(investigation.latency_ms / 1000).toFixed(2)}s`)
    }
    lines.push(`- **Thread ID:** ${investigation.thread_id}`)
    lines.push('')
    lines.push(`---`)
    lines.push(`*Generated by DevOps Copilot*`)
  }

  return lines.join('\n')
}

/**
 * Generate HTML report
 */
function toHtml(investigation: Investigation, includeMetadata = true): string {
  const markdown = toMarkdown(investigation, includeMetadata)

  // Simple markdown to HTML conversion
  let html = markdown
    .replace(/^### (.+)$/gm, '<h3>$1</h3>')
    .replace(/^## (.+)$/gm, '<h2>$1</h2>')
    .replace(/^# (.+)$/gm, '<h1>$1</h1>')
    .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
    .replace(/^- (.+)$/gm, '<li>$1</li>')
    .replace(/^---$/gm, '<hr>')
    .replace(/\n\n/g, '</p><p>')
    .replace(/\n/g, '<br>')

  // Wrap lists
  html = html.replace(/(<li>.*<\/li>)+/g, '<ul>$&</ul>')

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Investigation Report - ${investigation.thread_id}</title>
  <style>
    body {
      font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;
      max-width: 800px;
      margin: 0 auto;
      padding: 2rem;
      line-height: 1.6;
      color: #333;
    }
    h1 { color: #1a1a2e; border-bottom: 2px solid #6366f1; padding-bottom: 0.5rem; }
    h2 { color: #2d2d44; margin-top: 2rem; }
    h3 { color: #4a4a6a; }
    ul { padding-left: 1.5rem; }
    li { margin: 0.5rem 0; }
    hr { margin: 2rem 0; border: none; border-top: 1px solid #e5e7eb; }
    code { background: #f3f4f6; padding: 0.2rem 0.4rem; border-radius: 4px; }
    pre { background: #f3f4f6; padding: 1rem; border-radius: 8px; overflow-x: auto; }
    .metadata { background: #f9fafb; padding: 1rem; border-radius: 8px; margin-top: 2rem; }
    .confidence-high { color: #059669; }
    .confidence-medium { color: #d97706; }
    .confidence-low { color: #dc2626; }
  </style>
</head>
<body>
  ${html}
</body>
</html>`
}

/**
 * Generate JSON export
 */
function toJson(investigation: Investigation): string {
  return JSON.stringify(investigation, null, 2)
}

/**
 * Export investigation to specified format
 */
export function exportInvestigation(
  investigation: Investigation,
  options: ExportOptions
): string {
  const { format, includeMetadata = true } = options

  switch (format) {
    case 'markdown':
      return toMarkdown(investigation, includeMetadata)
    case 'html':
      return toHtml(investigation, includeMetadata)
    case 'json':
      return toJson(investigation)
    default:
      return toMarkdown(investigation, includeMetadata)
  }
}

/**
 * Download content as a file
 */
export function downloadFile(content: string, filename: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType })
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = filename
  document.body.appendChild(link)
  link.click()
  document.body.removeChild(link)
  URL.revokeObjectURL(url)
}

/**
 * Export and download investigation
 */
export function downloadInvestigation(
  investigation: Investigation,
  format: 'markdown' | 'json' | 'html'
): void {
  const content = exportInvestigation(investigation, { format })

  const extensions = {
    markdown: 'md',
    json: 'json',
    html: 'html'
  }

  const mimeTypes = {
    markdown: 'text/markdown',
    json: 'application/json',
    html: 'text/html'
  }

  const filename = `investigation-${investigation.thread_id}-${Date.now()}.${extensions[format]}`
  downloadFile(content, filename, mimeTypes[format])
}
